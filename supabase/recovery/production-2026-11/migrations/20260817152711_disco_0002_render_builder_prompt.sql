create or replace function disco.render_builder_prompt(p_order uuid)
returns text
language plpgsql
stable
security definer
set search_path to ''
as $fn$
declare
  v_bp uuid; c jsonb; v_opp uuid; o record; a record;
  v_for text; v_ag text; v_pkgv int; v_out text;
begin
  perform hlvs._require('hlvs.order.manage');

  select blueprint_id into v_bp from hlvs.software_creation_orders where id = p_order;
  if not found then
    raise exception 'order % not found', p_order using errcode = 'no_data_found';
  end if;

  select content into c from hlvs.product_blueprints where id = v_bp;
  v_opp := nullif(c ->> 'opportunity_id','')::uuid;
  if v_opp is null then
    raise exception 'blueprint % has no opportunity_id in content; cannot render a builder prompt without the source opportunity', v_bp
      using errcode = 'invalid_parameter_value';
  end if;

  select * into o from vstudio.opportunities where id = v_opp;
  select * into a from disco.assessments where opportunity_id = v_opp;
  select max(version) into v_pkgv from hlvs.prompt_packages where order_id = p_order;

  select string_agg(format('- [%s] %s%s', ev.evidence_type, ev.title,
           coalesce(' <'||ev.source_url||'>','')), E'\n' order by ev.created_at)
    into v_for from vstudio.evidence ev where ev.opportunity_id = v_opp;

  select string_agg(format('- [%s severity %s/10] %s', ea.failure_mode, ea.severity, ea.statement),
           E'\n' order by ea.severity desc)
    into v_ag from disco.evidence_against ea where ea.opportunity_id = v_opp;

  v_out :=
    '# BUILD PACKAGE - '||coalesce(o.title,'(untitled)')||E'\n'
  ||'Generated by HLVS Opportunity Discovery'||E'\n\n'
  ||'## 1 PRODUCT CONCEPT'||E'\n'||coalesce(c->>'concept', o.summary,'(not set)')||E'\n\n'
  ||'## 2 TARGET CUSTOMER'||E'\n'||coalesce(o.proposed_customer,'(not set)')||E'\n\n'
  ||'## 3 CUSTOMER PROBLEM'||E'\n'||coalesce(o.problem_statement,'(not set)')||E'\n\n'
  ||'## 4 VALUE PROPOSITION'||E'\n'||coalesce(c->>'value_proposition', a.product_gap,'(not set)')||E'\n\n'
  ||'## 5 SUPPORTING EVIDENCE'||E'\n'||coalesce(v_for,'(none recorded)')||E'\n\n'
  ||'## 6 COUNTER-EVIDENCE / MAJOR RISKS'||E'\n'
    ||coalesce(v_ag,'(none recorded - treat as UNASSESSED, not risk-free)')||E'\n'
    ||coalesce(E'\nAdditional risks: '||array_to_string(a.risks,'; '),'')||E'\n\n'
  ||'## 7 MVP SCOPE'||E'\n'||coalesce(a.mvp_scope,'(not set)')||E'\n\n'
  ||'## 8 FEATURE LIST'||E'\n'||coalesce(c->>'mvp_features','(not set)')||E'\n\n'
  ||'## 9 SCREENS'||E'\n'||coalesce(c->>'screens','(not set)')||E'\n\n'
  ||'## 10 NAVIGATION'||E'\n'||coalesce(c->>'navigation','(not set)')||E'\n\n'
  ||'## 11 DATA MODEL REQUIREMENTS'||E'\n'||coalesce(c->>'data_model','(not set)')||E'\n\n'
  ||'## 12 AUTHENTICATION REQUIREMENTS'||E'\n'
    ||coalesce(c->>'auth','Supabase Auth. RLS on every table. No service_role key in any client bundle.')||E'\n\n'
  ||'## 13 SUBSCRIPTION / MONETIZATION MODEL'||E'\n'
    ||coalesce(a.price_model,'(not set)')||' | '
    ||coalesce(a.suggested_price_low::text,'?')||' - '||coalesce(a.suggested_price_high::text,'?')||E'\n\n'
  ||'## 14 REVENUECAT REQUIREMENTS'||E'\n'
    ||coalesce(c->>'revenuecat','Required if iOS/Android; otherwise Stripe Checkout.')||E'\n\n'
  ||'## 15 SUPABASE / BACKEND REQUIREMENTS'||E'\n'
    ||coalesce(c->>'supabase','Postgres + Auth + RLS. Per-user/tenant scoping on every table.')||E'\n\n'
  ||'## 16 ANALYTICS / EVENTS'||E'\n'
    ||coalesce(c->>'analytics','signup, activation, paywall_view, subscribe, churn')||E'\n\n'
  ||'## 17 PRIVACY / REGULATORY'||E'\n'||coalesce(c->>'privacy','(not set)')||E'\n\n'
  ||'## 18 LAUNCH PRICING'||E'\n'||coalesce(c->>'launch_pricing','(not set)')||E'\n\n'
  ||'## 19 FIRST-100-USER ACQUISITION'||E'\n'
    ||coalesce(array_to_string(a.acquisition_channels,', '),'(not set)')||E'\n\n'
  ||'## 20 RECOMMENDED BUILDER'||E'\n'||coalesce(a.builder_recommendation,'requires_investigation')||E'\n\n'
  ||'## 21 BUILD COMPLEXITY'||E'\n'
    ||'build='||coalesce(a.build_difficulty::text,'unknown')
    ||' | acquisition='||coalesce(a.acquisition_difficulty::text,'unknown')
    ||' | recurring='||coalesce(a.recurring_potential::text,'unknown')
    ||' | low_touch='||coalesce(a.low_touch_potential::text,'unknown')||E'\n\n'
  ||'## 22 OPPORTUNITY SCORE AND CONFIDENCE'||E'\n'
    ||coalesce(a.score_gross::text,'?')||' gross - '||coalesce(a.score_penalty::text,'?')
    ||' counter-evidence = '||coalesce(a.score_net::text,'?')||' net'
    ||' | confidence '||coalesce(a.confidence,'unknown')||E'\n'
    ||coalesce('Rank rationale: '||a.rank_rationale,'')||E'\n\n'
  ||'## LINEAGE'||E'\n'
    ||'opportunity='||v_opp||E'\n'
    ||'blueprint='||v_bp||E'\n'
    ||'order='||p_order||E'\n'
    ||'governance_package_version=v'||coalesce(v_pkgv::text,'(none)')||E'\n'
    ||'ceo_decision='||coalesce((select d.id::text from vstudio.decisions d
         where d.opportunity_id = v_opp order by d.created_at desc limit 1),'(none)')||E'\n\n'
  ||'## GOVERNANCE (from hlvs.prompt_packages - authoritative)'||E'\n'
  ||'- Mandatory reuse analysis before writing new code'||E'\n'
  ||'- Prohibited duplication of existing HLG capabilities'||E'\n'
  ||'- Repository and branch restrictions apply'||E'\n'
  ||'- No live production deployment without CEO approval'||E'\n';

  return v_out;
end;
$fn$;

comment on function disco.render_builder_prompt is
  'Renders the 22-element builder package from blueprint content + vstudio evidence + disco assessment. Complements hlvs.generate_prompt_package (governance contract); does not replace or modify it.';