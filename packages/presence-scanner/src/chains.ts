const NORMALIZED = Object.fromEntries(
  Object.entries(CHAINS).map(([v, list]) => [v, list.map(normalizeName)]),
) as Record<Vertical, string[]>;

/** The chain name a business matches within its vertical, or undefined. */
export function matchChain(name: string, vertical: Vertical): string | undefined {
  const n = normalizeName(name);
  return NORMALIZED[vertical].find(
    (c) => c !== "" && (n === c || n.startsWith(`${c} `)),
  );
}
