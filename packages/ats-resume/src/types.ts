export type RequirementImportance =
  "critical" | "important" | "preferred" | "informational";

export type RequirementKind =
  | "qualification"
  | "experience"
  | "education"
  | "certification"
  | "software"
  | "hard_skill"
  | "soft_skill"
  | "leadership"
  | "responsibility"
  | "compliance"
  | "travel"
  | "physical"
  | "scope";

export interface JobRequirement {
  readonly id: UUID;
  readonly text: string;
  readonly kind: RequirementKind;
  readonly importance: RequirementImportance;
  /** Which part of the posting it came from — kept for auditability. */
  readonly sourceSection: string;
  /** Normalised terms this requirement is "about". */
  readonly terms: readonly string[];
  /** e.g. 5 for "5+ years of experience". */
  readonly yearsRequired?: number;
}

export type KeywordPriority = "high" | "medium" | "low";

export interface JobKeyword {
  readonly id: UUID;
  readonly term: string;
  readonly priority: KeywordPriority;
  readonly occurrences: number;
  /** Whether the term appears in a critical/important requirement. */
  readonly inRequirement: boolean;
}

