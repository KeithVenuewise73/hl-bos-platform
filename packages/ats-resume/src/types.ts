export type MatchStatus =
  "strong_match" | "partial_match" | "terminology_match" | "not_evidenced";

/** One row of the evidence matrix. */
export interface RequirementMatch {
  readonly id: UUID;
  readonly requirementId: UUID;
  readonly requirement: string;
  readonly importance: RequirementImportance;
  /** The candidate's own wording, quoted. Empty when nothing was found. */
  readonly evidence: string;
  /** Where that wording came from, e.g. "Amazon — Operations Manager". */
  readonly evidenceSource: string;
  readonly evidenceFactIds: readonly UUID[];
  readonly status: MatchStatus;
  readonly recommendedAction: string;
  readonly suggestedPlacement: readonly SectionKind[];
  /** 0..1 — how much of the requirement the evidence covers. */
  readonly coverage: number;
}

export interface TerminologyOpportunity {
  readonly id: UUID;
  readonly resumeWording: string;
  readonly jobWording: string;
  readonly recommendedRewrite: string;
  readonly evidenceFactIds: readonly UUID[];
  readonly requirementIds: readonly UUID[];
}

export interface KeywordAnalysis {
  readonly present: readonly JobKeyword[];
  /** Missing from the resume, but the candidate's evidence supports them. */
  readonly supportedMissing: readonly JobKeyword[];
  /** Missing, and nothing in the profile supports them. Never auto-inserted. */
  readonly unsupported: readonly JobKeyword[];
}

export interface ScoreBreakdown {
  readonly qualificationAlignment: number;
  readonly relevantExperience: number;
  readonly skillsAndKeywords: number;
  readonly quantifiedAccomplishments: number;
  readonly atsStructure: number;
}

/**
 * An INTERNAL optimisation score. It is not, and cannot be, the employer's ATS
 * score: we do not know their system, their weights, or their cutoffs. Every
 * surface that shows this number must say so.
 */
export interface MatchScore {
  readonly overall: number;
  readonly breakdown: ScoreBreakdown;
  readonly weights: ScoreBreakdown;
  readonly explanation: readonly string[];
}

export interface AtsFormatFinding {
  readonly id: UUID;
  readonly severity: "risk" | "warning" | "ok";
  readonly message: string;
  readonly fix: string;
}

export interface JobAnalysis extends RecordMeta {
  readonly profileId: UUID;
  readonly resumeId: UUID;
  readonly jobPostingId: UUID;
  readonly matches: readonly RequirementMatch[];
  readonly keywords: KeywordAnalysis;
  readonly terminology: readonly TerminologyOpportunity[];
  readonly scoreBefore: MatchScore;
  readonly scoreProjected: MatchScore;
  readonly formatFindings: readonly AtsFormatFinding[];
  readonly recommendations: readonly string[];
  /** Which engine produced this: the built-in rules engine, or Claude. */
  readonly engine: string;
  readonly isSample?: boolean;
}

