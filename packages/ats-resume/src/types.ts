/**
 * The ATS Resume Optimizer domain model.
 *
 * One rule shapes every type in this file: a FACT and a WORDING are different
 * things, and the type system is not allowed to blur them.
 *
 *   - A `CareerFact` is something that is true about the candidate. It carries
 *     a `source` saying how we know it.
 *   - A `GeneratedLine` is wording we produced. It carries the evidence it was
 *     derived from and a validation verdict.
 *
 * Wording may rephrase, reorder, compress and emphasise a fact. It may never
 * introduce one. Every generator in this package returns `GeneratedLine`s, and
 * `validateClaim()` is the only thing that may stamp one `verified`.
 */

/** Every record is keyed by a UUID (RFC 4122 v4, generated by `newId()`). */
export type UUID = string;

/** ISO-8601 timestamp, always UTC. */
export type Timestamp = string;

/** Fields every persisted record carries. */
export interface RecordMeta {
  readonly id: UUID;
  readonly createdAt: Timestamp;
  readonly updatedAt: Timestamp;
}

// ---------------------------------------------------------------------------
// Provenance
// ---------------------------------------------------------------------------

/**
 * How we know a fact.
 *
 * `generated_wording` is deliberately NOT a way to introduce a fact. A fact
 * whose source is `generated_wording` is a rephrasing of other facts, and it
 * must name them in `derivedFrom`. See `validateClaim()`.
 */
export type SourceStatus = "resume" | "user_confirmed" | "generated_wording";

/** Where a claim ended up after validation. */
export type ValidationStatus =
  "verified" | "user_confirmed" | "needs_confirmation" | "unsupported";

/** Only these two may be written into an exported document. */
export const EXPORTABLE_STATUSES: readonly ValidationStatus[] = [
  "verified",
  "user_confirmed",
];

